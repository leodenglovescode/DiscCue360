"""Rasterize Inter into the built-in DiscCue font tables (requires Pillow)."""
import sys
from pathlib import Path
from PIL import ImageFont

characters = list(range(32, 127)) + list(range(160, 256)) + [0x2013, 0x2014, 0x2018, 0x2019, 0x2026]
sizes = [(17, 500), (22, 500), (38, 650)]

with Path(sys.argv[2]).open("w") as output:
    print("/* Generated by make_font.py from Inter, licensed under the SIL OFL. */", file=output)
    for index, (size, weight) in enumerate(sizes):
        font = ImageFont.truetype(sys.argv[1], size)
        font.set_variation_by_axes([size, weight])
        alpha = []
        glyphs = []
        for point in characters:
            char = chr(point)
            mask, (x, y) = font.getmask2(char, mode="L", anchor="lt" if char == " " else "ls")
            width, height = mask.size
            glyphs.append((point, len(alpha), x, y, width, height, round(font.getlength(char))))
            alpha.extend(mask)
        print(f"static const uint8_t alpha_{index}[] = {{", file=output)
        for start in range(0, len(alpha), 32):
            print("    " + ",".join(str(v) for v in alpha[start:start+32]) + ",", file=output)
        print("};", file=output)
        print(f"static const Glyph glyphs_{index}[] = {{", file=output)
        for glyph in glyphs:
            print("    {" + ", ".join(str(v) for v in glyph) + "},", file=output)
        print("};", file=output)
